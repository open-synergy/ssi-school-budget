from odoo import fields, models


class SchoolBudgetComparativeResult(models.Model):
    """
    One row per target budget (a branch/center itself, plus every
    descendant unit) under a branch/center school_budget document,
    generated by action_simulate() (ssi_school_budget). Each row
    carries the target's revenue/expense/surplus figures twice: once
    with parent allocation included, once without — so management
    can see how much of a unit's budget comes from ancestor
    push-down.
    """

    _name = "school_budget_comparative_result"
    _description = "School Budget Comparative Result"

    budget_id = fields.Many2one(
        string="# Budget",
        comodel_name="school_budget",
        required=True,
        ondelete="cascade",
        help="The branch/center budget document (parent) this "
        "comparative result belongs to.",
    )
    target_budget_id = fields.Many2one(
        string="Target Budget",
        comodel_name="school_budget",
        help="The budget being summarized: the parent itself, or "
        "one of its descendant units.",
    )
    revenue = fields.Monetary(
        string="Revenue",
        currency_field="currency_id",
        help="Target's total revenue, with parent allocation included.",
    )
    expense = fields.Monetary(
        string="Expense",
        currency_field="currency_id",
        help="Target's total expense, with parent allocation included.",
    )
    cash_surplus = fields.Monetary(
        string="Cash Surplus",
        currency_field="currency_id",
    )
    accrual_surplus = fields.Monetary(
        string="Accrual Surplus",
        currency_field="currency_id",
    )
    revenue_no_alloc = fields.Monetary(
        string="Revenue (No Allocation)",
        currency_field="currency_id",
    )
    expense_no_alloc = fields.Monetary(
        string="Expense (No Allocation)",
        currency_field="currency_id",
    )
    cash_surplus_no_alloc = fields.Monetary(
        string="Cash Surplus (No Allocation)",
        currency_field="currency_id",
    )
    accrual_surplus_no_alloc = fields.Monetary(
        string="Accrual Surplus (No Allocation)",
        currency_field="currency_id",
    )
    currency_id = fields.Many2one(
        string="Currency",
        comodel_name="res.currency",
        related="budget_id.currency_id",
        store=True,
        compute_sudo=True,
    )
