from odoo import fields, models


class SchoolBudgetAllocationResult(models.Model):
    """
    One row per unit contributing to a branch/center school_budget
    document, generated by action_simulate() (ssi_school_budget).
    Snapshots the contribution percentage and the resulting
    contribution amount at the time of simulation.
    """

    _name = "school_budget_allocation_result"
    _description = "School Budget Allocation Result"

    budget_id = fields.Many2one(
        string="# Budget",
        comodel_name="school_budget",
        required=True,
        ondelete="cascade",
        help="The branch/center budget document (parent) this "
        "allocation result belongs to.",
    )
    child_budget_id = fields.Many2one(
        string="Child Budget",
        comodel_name="school_budget",
        help="The contributing unit budget.",
    )
    pct_up = fields.Float(
        string="UP Percentage",
    )
    pct_us = fields.Float(
        string="US Percentage",
    )
    contribution_up = fields.Monetary(
        string="Contribution UP",
        currency_field="currency_id",
    )
    contribution_us = fields.Monetary(
        string="Contribution US",
        currency_field="currency_id",
    )
    currency_id = fields.Many2one(
        string="Currency",
        comodel_name="res.currency",
        related="budget_id.currency_id",
        store=True,
        compute_sudo=True,
    )
